#!/usr/bin/env python3
"""Witness script for fig:lorenz-ramp (v5 printed section 3): renders the
constructed-chaos ramp from the exp_008 artifact files ONLY and prints every
number the manuscript cites. Never edited by hand after rendering; the figure
is regenerated by running this script.

Artifact: v3/exp_008_lorenz_construction/results/ramp.jsonl and lambda1.jsonl
(frozen brief + registered amendments, 2026-10-18).
"""
import json
import pathlib

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = pathlib.Path(__file__).resolve().parent
# Research-repo layout first, then the public artifact repo's flat layout.
RES = next(p for p in (HERE.parent.parent / "v3/exp_008_lorenz_construction/results",
                       HERE.parent / "experiments/exp_008_lorenz_construction/results")
           if p.is_dir())


def load(name):
    return [json.loads(l) for l in (RES / name).open()]


ramp = load("ramp.jsonl")
lam = sorted(load("lambda1.jsonl"), key=lambda r: r["r"])

fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(6.4, 5.2))

styles = {"identity": ("0.6", "s", "identity lens"),
          "classical": ("0.35", "o", "diagonal lens (classical)"),
          "optimised": ("0.0", "^", "diagonal lens (optimised)")}
for lens, (col, mk, lab) in styles.items():
    sel = sorted([r for r in ramp if r["region"] == "local_rho0.3"
                  and r["lens"] == lens and r["r"] <= 1.3], key=lambda r: r["r"])
    ax1.plot([r["r"] for r in sel], [r["s"] for r in sel], marker=mk, ms=3.2,
             color=col, lw=0.9, label=lab)
ax1.axhline(0, color="k", lw=0.6)
ax1.axvline(0.7, color="k", lw=0.6, ls=":")
ax1.set_ylim(-2.4, 1.0)
ax1.annotate(r"derived flip $1-\rho=0.7$", (0.71, -2.25), fontsize=8)
ax1.set_xlabel(r"$r$")
ax1.set_ylabel(r"certified rate $s$, declared box $\rho=0.3$")
ax1.legend(fontsize=7.5, loc="lower left", framealpha=0.95)

ax2.plot([r["r"] for r in lam], [r["lambda1_mean"] for r in lam], "k.-",
         lw=0.8, ms=3)
ax2.fill_between([r["r"] for r in lam], [r["lambda1_min"] for r in lam],
                 [r["lambda1_max"] for r in lam], color="0.82")
ax2.axhline(0, color="k", lw=0.6)
ax2.axvline(1.0, color="k", lw=0.6, ls=":")
ax2.set_ylim(-1.15, 1.1)
ax2.annotate("certification ends\n($r\\leq 1-\\rho$, no lens passes beyond $r=1$)",
             (1.6, 0.62), fontsize=8)
ax2.annotate("measured $\\lambda_1$\ncrosses zero", (23.3, -1.0), fontsize=8,
             ha="right")
ax2.set_xlabel(r"$r$")
ax2.set_ylabel(r"measured $\lambda_1$ (8 seeds, min--max band)")

fig.tight_layout()
fig.savefig(HERE / "lorenz_ramp.pdf")

# numbers the manuscript prints, from the artifact only
flips = {}
for region in ["local_rho0.1", "local_rho0.3", "local_rho0.5"]:
    for lens in ["identity", "classical", "optimised"]:
        passing = [r["r"] for r in ramp if r["region"] == region
                   and r["lens"] == lens and r["pass"]]
        flips[(region, lens)] = max(passing) if passing else None
print("flips:", flips)
print("identity passes:", sum(1 for r in ramp if r["lens"] == "identity" and r["pass"]))
print("passes at r>1:", sum(1 for r in ramp if r["pass"] and r["r"] > 1))
print("global_trap passes:", sum(1 for r in ramp if r["region"] == "global_trap" and r["pass"]))
cross = next((row["r"] for row in lam if row["lambda1_mean"] > 0.01), None)
print("lambda1 first >0.01 at r =", cross)
print("rows total:", len(ramp))
sound = load("soundness.jsonl")
print("soundness checks:", len(sound), " violations:",
      sum(r["violations"] for r in sound),
      " worst ratio:", max(r["worst_ratio_vs_bound"] for r in sound))
